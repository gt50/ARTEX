//intentItem is an exploration direction of add_intent batch/single item.
type intentItem struct {
	Summary   string            `json:"summary"`
	AssetIDs  []json.RawMessage `json:"asset_ids"`
	ParentIDs []json.RawMessage `json:"parent_ids"`
	Priority  int               `json:"priority"`
}

//addOneIntent creates an intent node and connects it to the upstream bloodline, returning the id.
//Constraint: Intents can only be anchored on confirmed knowledge - each parent_id must be an existing fact/finding
//Node (cannot be attached to other intents/goals/prompts). Leave parent_ids blank for the new direction at the top level, and connect the origin fact at the bottom.
//This way "each intent is connected to a fact node and is discovery-driven rather than planned out of thin air" is enforced from the creation path.
func (t *ToolSet) addOneIntent(it intentItem) (int64, error) {
	if strings.TrimSpace(it.Summary) == "" {
		return 0, fmt.Errorf("summary cannot be empty")
	}
	//Verify the anchor point first (before building a node to avoid bad anchor points leaving orphan intentions).
	parents := pidList(it.ParentIDs)
	for _, pidv := range parents {
		n, err := t.ts.GetNodeWithSources(pidv)
		if err != nil || n == nil {
			return 0, fmt.Errorf("parent_id %d does not exist in this task or a directly linked task: parent_ids must identify existing fact/finding nodes; leave parent_ids empty for a new top-level direction", pidv)
		}
		if n.Kind != db.KindFact && n.Kind != db.KindFinding {
			return 0, fmt.Errorf("parent_id %d is a %q node and cannot anchor an intent: intents may only anchor to confirmed fact/finding nodes, not intents/goals/hints; leave parent_ids empty for a new top-level direction", pidv, n.Kind)
		}
	}
	priority := it.Priority
	if priority == 0 {
		priority = 5
	}
	anchors := pidList(it.AssetIDs)
	//Asset interception: If the asset bound to an intent hits the system asset interception rules, the intent is prohibited from being issued.
	if t.as != nil && len(anchors) > 0 {
		hits, err := t.as.CheckAssetsIntercept(t.taskID, anchors)
		if err != nil {
			return 0, fmt.Errorf("asset intercept validation failed: %w", err)
		}
		if len(hits) > 0 {
			var b strings.Builder
			fmt.Fprintf(&b, "Assets bound to intent \"%s\" failed testing-scope validation; stop testing the affected assets: ", it.Summary)
			for _, h := range hits {
				fmt.Fprintf(&b, "\n - %s", h.Describe())
			}
			return 0, fmt.Errorf("%s", b.String())
		}
	}
	payload := map[string]any{"summary": it.Summary}
	if len(anchors) > 0 {
		payload["asset_ids"] = anchors
	}
	id, err := t.ts.AddIntent(payload, priority, anchors, "planner")
	if err != nil {
		return 0, err
	}
	// upstream lineage: link each (validated) fact/finding parent → this intent, so
	// "multiple facts combine into one new intent" is expressible.
	for _, parent := range parents {
		_ = t.ts.Link(parent, db.RelDerivedFrom, id)
	}
	// a top-level intent (no explicit parent) connects to the origin fact, so every
	// intent still traces back to a fact node — at task start the only fact is the
	// origin, and the first intents derive from it.
	if len(parents) == 0 {
		if origin, _ := t.ts.OriginFactID(); origin > 0 {
			_ = t.ts.Link(origin, db.RelDerivedFrom, id)
		}
	}
	return id, nil
}

func (t *ToolSet) addIntent() actool.CoreTool {
	return t.writeExpTool("add_intent", "Add exploration directions to the frontier and link them into the exploration graph. An intent is an open exploration direction, not a fixed type; describe what to explore/verify/exploit in one summary sentence.\n"+
		"★ Prefer batches: submit new directions from one round in the intents array to reduce calls. Returns ids in matching order (failed items have id=0; see errors). For one intent, omit intents and use the top-level summary.",
		obj(map[string]any{
			"intents":    map[string]any{"type": "array", "description": "Preferred: array of new exploration directions, processed in order. Each item has the same fields as the top level (summary/asset_ids/parent_ids/priority). Returned ids match the array length and order.", "items": map[string]any{"type": "object"}},
			"summary":    str("Single intent: one sentence explaining what to explore and why. A clear direction does not depend on asset IDs."),
			"asset_ids":  map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Target asset IDs for this direction (provide whenever possible; zero, one, or several). Use asset IDs from list_assets, not exploration-node IDs. Include the sites/endpoints/parameters/hosts being tested. Supply IDs whenever specific assets are targeted; this structured association supports coverage deduplication and asset links. Leave empty only for genuinely global reconnaissance without specific targets."},
			"parent_ids": map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Optional upstream anchor IDs (zero, one, or several): confirmed facts/findings that justify this direction. Only existing fact/finding node IDs are allowed, not intent/goal/hint IDs. Anchor intents in confirmed knowledge. Provide several IDs when facts jointly motivate an intent. For new top-level reconnaissance, leave empty; the task origin fact is linked automatically."},
			"priority":   intp("Priority 0–10 (default 5)"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			var a struct {
				Intents    []intentItem `json:"intents"`
				intentItem              //Single mode: top summary/asset_ids/parent_ids/priority
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Intents) > 0
			items := a.Intents
			if !batch {
				items = []intentItem{a.intentItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			createdAny := false
			for i, it := range items {
				id, err := t.addOneIntent(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				createdAny = true
			}

			//Directly cast the intention by the main agent → If the task is done (goalless branch without open goal), put it
			//Pull back to running so that the worker can execute this intention. resumeTask is only accessed by the main agent's Chat
			//(SetResumeTask); the planner's ToolSet is nil, so the planner adjusts add_intent during this period.
			//no-op, does not affect its normal production intention. The intention node has been built (open) on it and will not be mistakenly drained when resurrected.
			if createdAny && t.resumeTask != nil {
				t.resumeTask()
			}

			if !batch { //Single: keep the original return
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("intent created: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

