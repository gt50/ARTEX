// assetRef converts an asset ID to the asset reference attached to a finding (label
// precedence matches the backend coverageNodeLabel: URL > domain > IP > application).
// These references attach findings to assets in the "By asset" tree.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

